const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { startServer } = require('../serve.cjs');
const { createClient } = require('../client.cjs');
test('HTTP API 完成创建、隔离读取、目标评分、指标、清理及签名结果读取', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'career-api-test-'));
  const { server, store, baseUrl } = await startServer({ dataRoot: root, port: 0 });
  t.after(async () => { store.close(); await new Promise(resolve => server.close(resolve)); if (path.dirname(path.resolve(root)) !== path.resolve(os.tmpdir()) || !path.basename(root).startsWith('career-api-test-')) throw new Error('清理路径不安全'); await fs.rm(root, { recursive: true, force: true }); });
  const client = await createClient({ baseUrl, token: store.adminToken });
  const scenarios = await client.listScenarios(); assert.equal(scenarios.scenarios.length, 8);
  const one = await client.createRun({ scenarioId: 'baseline', goal: 'fill', seed: 42 });
  const two = await client.createRun({ scenarioId: 'baseline', goal: 'preview', seed: 42 });
  const auth = { Authorization: 'Bearer ' + one.accessToken, 'Content-Type': 'application/json' };
  assert.equal((await fetch(baseUrl + `/api/runs/${two.id}/state`, { headers: auth })).status, 401);
  assert.equal((await fetch(baseUrl + `/api/runs/${one.id}/end`, { method: 'POST', headers: auth, body: '{}' })).status, 403);
  const stateView = await client.getState(one.id);
  assert.equal(stateView.manifest.seed, 42); assert.equal('expected' in stateView, false); assert.equal('scenario' in stateView, false);
  const raw = structuredClone(store.get(one.id).scenario.expected);
  let revision = stateView.revision;
  const upload = await fetch(baseUrl + `/api/runs/${one.id}/files/resume`, { method: 'POST', headers: auth, body: JSON.stringify({ name: 'same-content-renamed.pdf', base64: (await fs.readFile(one.attachmentPath)).toString('base64') }) });
  assert.equal(upload.status, 200); revision = (await upload.json()).revision;
  const saved = await fetch(baseUrl + `/api/runs/${one.id}/state`, { method: 'PUT', headers: auth, body: JSON.stringify({ revision, state: raw, events: [{ type: 'field_change', path: 'personal.name' }] }) });
  assert.equal(saved.status, 200);
  const second = await client.getState(two.id); assert.equal(second.state.personal.name, undefined); assert.deepEqual(second.state.files, {});
  await client.addMetrics(one.id, { tokens: { input: 100, output: 50 }, retries: 2 });
  const result = await client.endRun(one.id, { cleanup: true }); assert.equal(result.payload.report.passed, true);
  assert.equal((await client.getResult(one.id)).signature, result.signature);
  await assert.rejects(client.getState(one.id), { code: 'RUN_NOT_FOUND' });
  const events = await client.getEvents(two.id); assert.ok(events.events.length); assert.deepEqual((await client.getEvents(two.id, events.cursor)).events, []);
  assert.equal((await fetch(baseUrl + '/api/scenarios')).status, 401);
  assert.equal((await fetch(baseUrl + '/api/scenarios', { headers: { Authorization: 'Bearer ' + store.adminToken, Origin: 'https://example.com' } })).status, 403);
  assert.equal((await fetch(baseUrl + '/signing-private.pem')).status, 404);
  const ended = await client.endRun(two.id); assert.equal(ended.payload.report.passed, false); await client.cleanupRun(two.id);
});
